/// 인증 화면의 모드를 정의하는 enum.
///
/// [AuthScreen]에서 사용자가 현재 어떤 인증 흐름에 있는지 추적.
/// UI 표시와 폼 유효성 검사 로직에 영향을 줌.
enum AuthMode {
  /// 로그인 모드
  /// - 이메일 + 비밀번호 입력
  /// - 기존 계정으로 로그인
  signIn,

  /// 회원가입 모드
  /// - 이메일 + 비밀번호 + 비밀번호 확인 입력
  /// - 새 계정 생성 및 인증 메일 발송
  signUp,

  /// 비밀번호 재설정 모드
  /// - 이메일만 입력
  /// - 비밀번호 재설정 링크 이메일 발송
  resetPassword,
}
